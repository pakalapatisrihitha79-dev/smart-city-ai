/**
 * Builds localized briefing text dynamically for any language
 */
export function buildLocalizedBriefing(
  lang: SupportedLanguage,
  areaName: string,
  zone: {
    traffic: string;
    aqi: number;
    aqiStatus: string;
    pm25: number;
    weather: string;
    temp: number;
    humidity: number;
    rainfallMm: number;
    floodRiskPct: number;
    waterStatus: string;
    energyDemandKw: number;
    healthScore: number;
  }
) {
  const isTe = lang === "te";
  const isHi = lang === "hi";
  const isEs = lang === "es";
  const isFr = lang === "fr";
  const isAr = lang === "ar";
  const isZh = lang === "zh";

  const speed = zone.traffic === "Low" ? "48" : zone.traffic === "Moderate" ? "32" : "18";

  let thingsToKnow: string[] = [];
  let thingToWatch = "";
  let recommendation = "";

  if (isTe) {
    thingsToKnow = [
      `${areaName} లో ట్రాఫిక్ ప్రవాహం ప్రస్తుతం ${zone.traffic} గా ఉంది (సగటు వేగం ${speed} కి.మీ/గం).`,
      `గాలి నాణ్యత సూచీ (AQI) ${zone.aqi} (${zone.aqiStatus}) గా ఉంది, PM2.5 స్థాయిలు ${zone.pm25} µg/m³ గా నమోదయ్యాయి.`,
      `వాతావరణం ${zone.weather}, ఉష్ణోగ్రత ${zone.temp}°C, తేమ ${zone.humidity}%.`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `అధిక వర్షపాతం (${zone.rainfallMm} మి.మీ) వల్ల వరద ప్రమాదం ${zone.floodRiskPct}% కి పెరిగింది.`
        : zone.waterStatus === "Anomaly Leakage"
        ? `వాటర్ వాచ్ సెన్సార్ మునిసిపల్ గ్రిడ్‌లో గురుతించిన నీటి లీకేజీ.`
        : `విద్యుత్ డిమాండ్ గరిష్ట స్థాయికి చేరుతోంది (${zone.energyDemandKw} kW).`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "ట్రాఫిక్ రద్దీని నివారించడానికి 20 నిమిషాల ముందే బయలుదేరండి లేదా మెట్రో రైలును ఉపయోగించండి."
        : zone.aqi > 100
        ? "గాలిలో కాలుష్యం ఎక్కువ ఉంది. బయట వ్యాయామాలను తగ్గించండి."
        : "ప్రయాణానికి మరియు బహిరంగ కార్యకలాపాలకు అనుకూలమైన సమయం.";
  } else if (isHi) {
    thingsToKnow = [
      `${areaName} में यातायात प्रवाह वर्तमान में ${zone.traffic} है (औसत गति ${speed} किमी/घंटा)।`,
      `वायु गुणवत्ता सूचकांक ${zone.aqi} (${zone.aqiStatus}) पर है, जिसमें PM2.5 स्तर ${zone.pm25} µg/m³ है।`,
      `मौसम ${zone.weather} है, तापमान ${zone.temp}°C और आर्द्रता ${zone.humidity}% है।`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `भारी बारिश (${zone.rainfallMm}mm) के कारण बाढ़ का खतरा ${zone.floodRiskPct}% बढ़ गया है।`
        : zone.waterStatus === "Anomaly Leakage"
        ? `वाटर वॉच सेंसर ने जल आपूर्ति ग्रिड में रिसाव का पता लगाया है।`
        : `बिजली की मांग चरम क्षमता (${zone.energyDemandKw} kW) के करीब है।`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "यातायात भीड़ से बचने के लिए 20 मिनट पहले निकलें या मेट्रो का उपयोग करें।"
        : zone.aqi > 100
        ? "बाहरी प्रदूषण अधिक है। बाहर भारी व्यायाम से बचें।"
        : "यात्रा और बाहरी गतिविधियों के लिए आदर्श स्थिति।";
  } else if (isEs) {
    thingsToKnow = [
      `El flujo de tráfico en ${areaName} es ${zone.traffic.toLowerCase()} a una velocidad promedio de ${speed} km/h.`,
      `Índice de Calidad del Aire es ${zone.aqi} (${zone.aqiStatus}) con PM2.5 a ${zone.pm25} µg/m³.`,
      `Clima: ${zone.weather.toLowerCase()} a ${zone.temp}°C con ${zone.humidity}% de humedad.`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `Alta precipitación (${zone.rainfallMm}mm) aumenta el riesgo de inundación a ${zone.floodRiskPct}%.`
        : `Demanda de energía cerca de capacidad máxima (${zone.energyDemandKw} kW).`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "Salga 20 minutos antes o use el Metro para evitar la congestión."
        : "Condiciones óptimas de movilidad urbana.";
  } else if (isFr) {
    thingsToKnow = [
      `Le trafic à ${areaName} est actuellement ${zone.traffic.toLowerCase()} à une vitesse moyenne de ${speed} km/h.`,
      `L'indice de qualité de l'air est à ${zone.aqi} (${zone.aqiStatus}) avec PM2.5 à ${zone.pm25} µg/m³.`,
      `Météo: ${zone.weather.toLowerCase()} à ${zone.temp}°C avec ${zone.humidity}% d'humidité.`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `Forte pluie (${zone.rainfallMm}mm) augmentant le risque d'inondation à ${zone.floodRiskPct}%.`
        : `Demande d'énergie proche du pic (${zone.energyDemandKw} kW).`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "Partez 20 minutes plus tôt ou prenez le métro pour éviter les bouchons."
        : "Conditions de circulation idéales.";
  } else if (isAr) {
    thingsToKnow = [
      `حركة المرور في ${areaName} حالياً ${zone.traffic} بمتوسط سرعة ${speed} كم/س.`,
      `مؤشر جودة الهواء عند ${zone.aqi} (${zone.aqiStatus}) ومستوى PM2.5 هو ${zone.pm25} µg/m³.`,
      `الطقس ${zone.weather} عند درجة حرارة ${zone.temp}°م ورطوبة ${zone.humidity}%.`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `أمطار غزيرة (${zone.rainfallMm} ملم) تزيد من خطر الفيضانات إلى ${zone.floodRiskPct}%.`
        : `الطلب على الطاقة يقترب من الحد الأقصى (${zone.energyDemandKw} كيلوواط).`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "ينصح بالتحرك قبل 20 دقيقة أو استخدام المترو لتجنب الازدحام."
        : "ظروف التنقل ممتازة ومثالية للأنشطة الخارجية.";
  } else if (isZh) {
    thingsToKnow = [
      `${areaName} 当前交通状况为 ${zone.traffic}，平均车速约 ${speed} km/h。`,
      `空气质量指数 AQI 为 ${zone.aqi}（${zone.aqiStatus}），PM2.5 浓度为 ${zone.pm25} µg/m³。`,
      `天气：${zone.weather}，气温 ${zone.temp}°C，湿度 ${zone.humidity}%。`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `强降雨（${zone.rainfallMm}mm）导致低洼地区积涝风险上升至 ${zone.floodRiskPct}%。`
        : `电力负荷接近峰值容量（${zone.energyDemandKw} kW）。`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "建议提前20分钟出发或乘坐轨道交通避开拥堵。"
        : "当前城市运行状态优良，适合出行。";
  } else {
    // Default English
    thingsToKnow = [
      `Traffic flow in ${areaName} is currently ${zone.traffic.toLowerCase()} with average speeds around ${speed} km/h.`,
      `Air Quality Index is measured at ${zone.aqi} (${zone.aqiStatus}) with PM2.5 levels at ${zone.pm25} µg/m³.`,
      `Weather is ${zone.weather.toLowerCase()} at ${zone.temp}°C with ${zone.humidity}% humidity.`,
    ];
    thingToWatch =
      zone.rainfallMm > 15
        ? `High rainfall (${zone.rainfallMm}mm) increasing localized flood risk to ${zone.floodRiskPct}% in lower zones.`
        : zone.waterStatus === "Anomaly Leakage"
        ? `Water Watch sensor flagged a pressure anomaly in municipal sub-grid.`
        : zone.traffic === "High" || zone.traffic === "Congested"
        ? `Vehicle congestion building up along primary arterial connections.`
        : `Power demand approaching peak capacity (${zone.energyDemandKw} kW).`;
    recommendation =
      zone.traffic === "High" || zone.traffic === "Congested"
        ? "Consider departing 20 minutes earlier or using Metro transit to bypass congestion."
        : zone.aqi > 100
        ? "Sensitivity to outdoor particulates elevated. Limit strenuous outdoor exercises."
        : zone.rainfallMm > 20
        ? "Maintain caution near low-lying underpasses and monitor official flood advisories."
        : "Optimal mobility conditions. Ideal window for commuting and outdoor activities.";
  }

  return { thingsToKnow, thingToWatch, recommendation };
}
